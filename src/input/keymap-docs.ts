/**
 * 键位文档渲染（S03 §5）。README 的键位区块与 `--help` 的键位段都从这里出，
 * 输入是 `src/input/keymap.ts` 的绑定（S01）加 `src/controls/feature-keys.ts`
 * 的静态功能键清单（S02）；不在这里再维护第二份键位表。
 *
 * `scripts/keymap-docs.mjs` 用同一份渲染函数写 README 并做 `--check` 比对。
 */
import type { KeyBinding, KeySpec, Scope } from './keymap.ts'

const KEY_NAMES: Record<string, string> = {
  enter: 'Enter',
  tab: 'Tab',
  backspace: 'Backspace',
  escape: 'Esc',
  up: 'Up',
  down: 'Down',
  left: 'Left',
  right: 'Right',
  home: 'Home',
  end: 'End',
  pageup: 'PageUp',
  pagedown: 'PageDown',
  insert: 'Insert',
  delete: 'Delete',
}

const SCOPE_LABELS: Record<Scope, { zh: string; en: string }> = {
  input: { zh: '输入', en: 'Input' },
  idle: { zh: '空闲', en: 'Idle' },
  running: { zh: '运行中', en: 'Running' },
  overlay: { zh: '覆盖层', en: 'Overlay' },
  selection: { zh: '选区', en: 'Selection' },
}

export type DocLang = 'zh' | 'en'

function keyLabel(spec: KeySpec): string {
  const parts: string[] = []
  if (spec.ctrl === true) parts.push('Ctrl')
  if (spec.alt === true) parts.push('Alt')
  if (spec.shift === true) parts.push('Shift')
  if (spec.meta === true) parts.push('Cmd')
  if (spec.name === 'char') parts.push((spec.text ?? '').toUpperCase())
  else parts.push(KEY_NAMES[spec.name] ?? spec.name)
  return parts.join('+')
}

function keysLabel(binding: KeyBinding): string {
  return binding.keys.map(keyLabel).join(' / ')
}

function scopeLabel(binding: KeyBinding, lang: DocLang): string {
  if (!binding.scopes || binding.scopes.length === 0) return lang === 'zh' ? '全局' : 'Any'
  return binding.scopes.map((scope) => SCOPE_LABELS[scope][lang]).join(' / ')
}

function description(binding: KeyBinding, lang: DocLang): string {
  if (lang === 'zh') return binding.description
  return binding.descriptionEn ?? binding.description
}

/** Markdown 表格单元格转义：描述里出现 `|` 或反引号不能把表写断。 */
function escapeCell(text: string): string {
  return text.replaceAll('\\', '\\\\').replaceAll('|', '\\|').replaceAll('`', '\\`')
}

/** 渲染 README 的键位表（两列：快捷键、作用；范围并进作用列，避免宽表折行）。 */
export function renderKeymapMarkdown(bindings: readonly KeyBinding[], lang: DocLang): string {
  const rows = bindings.map((binding) => {
    const scope = escapeCell(scopeLabel(binding, lang))
    return `| \`${keysLabel(binding)}\` | ${escapeCell(description(binding, lang))}（${scope}） |`
  })
  const header = lang === 'zh' ? '| 快捷键 | 作用 |' : '| Keys | Action |'
  return [header, '| --- | --- |', ...rows].join('\n')
}

/** 渲染 `--help` 的键位段（纯文本，按最长的键位串对齐）。 */
export function renderKeymapHelp(bindings: readonly KeyBinding[], lang: DocLang = 'zh'): string {
  const width = Math.max(...bindings.map((binding) => keysLabel(binding).length))
  const lines = bindings.map((binding) => {
    const scope = scopeLabel(binding, lang)
    return `  ${keysLabel(binding).padEnd(width)}  ${description(binding, lang)}（${scope}）`
  })
  return [lang === 'zh' ? '键位：' : 'Keys:', ...lines].join('\n')
}

/** README 里生成区块的边界标记；`--write` 与 `--check` 都按这对标记定位。 */
export const KEYMAP_START = '<!-- keymap:start (generated by scripts/keymap-docs.mjs) -->'
export const KEYMAP_END = '<!-- keymap:end -->'

function countOf(text: string, needle: string): number {
  return text.split(needle).length - 1
}

/** 把渲染结果替换进 README 文本；标记缺失或重复都报错，不猜位置。 */
export function replaceKeymapBlock(
  text: string,
  rendered: string,
): { ok: true; text: string } | { ok: false; reason: string } {
  const starts = countOf(text, KEYMAP_START)
  const ends = countOf(text, KEYMAP_END)
  if (starts !== 1 || ends !== 1) {
    return {
      ok: false,
      reason: `expected exactly one marker pair, found start=${starts} end=${ends}`,
    }
  }
  const start = text.indexOf(KEYMAP_START)
  const end = text.indexOf(KEYMAP_END)
  if (start < 0 || end < 0 || end < start) {
    return { ok: false, reason: `missing markers ${KEYMAP_START} / ${KEYMAP_END}` }
  }
  const head = text.slice(0, start + KEYMAP_START.length)
  const tail = text.slice(end)
  return { ok: true, text: `${head}\n${rendered}\n${tail}` }
}
